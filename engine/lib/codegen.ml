open Ir

let rec expr_to_cpp e =
  let operand x =
    match x with
    | Int n when n < 0 -> "(" ^ string_of_int n ^ ")"
    | Int _ | Param _ | Var _ | Mod _ -> expr_to_cpp x
    | _ -> "(" ^ expr_to_cpp x ^ ")"
  in
  match e with
  | Int n -> string_of_int n
  | Param x | Var x -> x
  | Add (a, b) -> Printf.sprintf "%s + %s" (operand a) (operand b)
  | Sub (a, b) -> Printf.sprintf "%s - %s" (operand a) (operand b)
  | Mod (a, b) -> Printf.sprintf "emod(%s, %s)" (expr_to_cpp a) (expr_to_cpp b)

let locals body =
  let rec collect stmts =
    List.concat_map
      (fun s ->
        match s with
        | NaRead { dst; _ } | Load { dst; _ } | Let { dst; _ } -> [ dst ]
        | For { body; _ } -> collect body
        | _ -> [])
      stmts
  in
  List.sort_uniq compare (collect body)

let line b ind s =
  (* indents are 2 spaces because llvm styling is best :) *)
  Buffer.add_string b (String.make (2 * ind) ' ');
  Buffer.add_string b s;
  Buffer.add_char b '\n'

let order sigma acc = Ord.to_cpp (List.assoc acc.label sigma)

let loops_to_string loops =
  String.concat ", " (List.map (fun (x, k) -> Printf.sprintf "%s=%d" x k) loops)

let note sigma reqs acc =
  let o = Ord.to_string (List.assoc acc.label sigma) in
  match Solve.reason reqs acc.label with
  | Some r ->
      Printf.sprintf "  // %s: %s, %s (%s)" acc.label o r.reason
        (loops_to_string r.loops)
  | None -> Printf.sprintf "  // %s: %s" acc.label o

let rec emit_stmt b sigma reqs ind s =
  match s with
  | NaRead { dst; arr; idx } ->
      line b ind (Printf.sprintf "%s = %s[%s];" dst arr (expr_to_cpp idx))
  | NaWrite { arr; idx; value } ->
      line b ind
        (Printf.sprintf "%s[%s] = %s;" arr (expr_to_cpp idx) (expr_to_cpp value))
  | Load { dst; acc } ->
      line b ind
        (Printf.sprintf "%s = %s.load(%s);%s" dst acc.atom (order sigma acc)
           (note sigma reqs acc))
  | Store { acc; value } ->
      line b ind
        (Printf.sprintf "%s.store(%s, %s);%s" acc.atom (expr_to_cpp value)
           (order sigma acc) (note sigma reqs acc))
  | Await { acc; bound } ->
      line b ind
        (Printf.sprintf "while (%s.load(%s) < %s) {}%s" acc.atom
           (order sigma acc) (expr_to_cpp bound) (note sigma reqs acc))
  | Let { dst; value } ->
      line b ind (Printf.sprintf "%s = %s;" dst (expr_to_cpp value))
  | Assert { lhs; rhs } ->
      line b ind
        (Printf.sprintf "assert(%s == %s);" (expr_to_cpp lhs) (expr_to_cpp rhs))
  | For { var; lo; hi; body } ->
      line b ind
        (Printf.sprintf "for (int %s = %s; %s < %s; ++%s) {" var
           (expr_to_cpp lo) var (expr_to_cpp hi) var);
      List.iter (emit_stmt b sigma reqs (ind + 1)) body;
      line b ind "}"

let emit_thread b sigma reqs th =
  line b 0 (Printf.sprintf "void *%s(void *) {" th.thread_name);
  List.iter
    (fun x -> line b 1 (Printf.sprintf "int %s = 0;" x))
    (locals th.body);
  List.iter (emit_stmt b sigma reqs 1) th.body;
  line b 1 "return nullptr;";
  line b 0 "}";
  line b 0 ""

let emit prog sigma reqs =
  let b = Buffer.create 4096 in
  line b 0 "// Generated by engine.";
  line b 0 "#include <atomic>";
  line b 0 "#include <cassert>";
  line b 0 "#include <pthread.h>";
  line b 0 "";
  List.iter
    (fun (name, n) -> line b 0 (Printf.sprintf "constexpr int %s = %d;" name n))
    prog.params;
  line b 0 "";
  List.iter
    (fun d ->
      line b 0 (Printf.sprintf "int %s[%s];" d.arr_name (expr_to_cpp d.size)))
    prog.arrays;
  line b 0 "";
  List.iter
    (fun d ->
      line b 0 (Printf.sprintf "std::atomic<int> %s{%d};" d.atom_name d.init))
    prog.atomics;
  line b 0 "";
  line b 0 "// Euclidean mod";
  line b 0 "static int emod(int a, int b) {";
  line b 1 "int r = a % b;";
  line b 1 "return r < 0 ? r + b : r;";
  line b 0 "}";
  line b 0 "";
  List.iter (emit_thread b sigma reqs) prog.threads;
  line b 0 "int main() {";
  let n = List.length prog.threads in
  line b 1 (Printf.sprintf "pthread_t threads[%d];" n);
  List.iteri
    (fun k th ->
      line b 1
        (Printf.sprintf "pthread_create(&threads[%d], nullptr, %s, nullptr);" k
           th.thread_name))
    prog.threads;
  line b 1
    (Printf.sprintf
       "for (int k = 0; k < %d; ++k) pthread_join(threads[k], nullptr);" n);
  line b 1 "return 0;";
  line b 0 "}";
  Buffer.contents b
